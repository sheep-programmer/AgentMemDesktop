/**
 * 按文档拼出「正文 + 带偏移的切片」。
 *
 * demo（mock）模式此前只给一段固定的示例正文，切片也不带字符偏移——于是从对话点
 * 「查看原文」进到阅读器，既定位不到、也高亮不了，而这正是这个产品最该被看到的动作。
 * 这里由切片**现拼**正文，偏移是拼的时候算出来的，天然自洽。
 */
export function mockDocumentBundle(documentId: string): {
  markdown: string;
  chunks: ChunkItem[];
} {
  const own = mockChunks.filter((chunk) => chunk.document_id === documentId);
  const source = own.length > 0 ? own : mockChunks;
  const title =
    mockDocuments.find((doc) => doc.id === documentId)?.title ?? '示例文档';

  let markdown = `# ${title}\n\n`;
  const chunks: ChunkItem[] = [];
  for (const chunk of source) {
    const heading = chunk.heading_path ? `## ${chunk.heading_path}\n\n` : '';
    markdown += heading;
    const start = markdown.length;
    markdown += chunk.content;
    chunks.push({ ...chunk, char_start: start, char_end: markdown.length });
    markdown += '\n\n';
  }
  return { markdown, chunks };
}

